import { test } from 'node:test'
import assert from 'node:assert/strict'
import { apply, localizeMessage } from '../lib/context.js'

const message = (kind, text, source = {}) => ({
  id: 'same-id', role: 'user', content: [{ type: 'text', text }], source: { kind, ...source },
})
const body = 'DSH 是本项目研究对象。\nInstructions from: ~/.dsh/AGENTS.md\n\nDo not change this original body.'
const intro = 'The following workspace instructions may be relevant to your work. Use them as guidance when applicable. More specific instructions take precedence over broader ones. They do not override system, developer, or direct user instructions.'

test('中文化工作区框架与来源标签，逐字保留 AGENTS 正文及原始来源元数据', () => {
  const original = message('agent-instructions', `<system-reminder>\n${intro}\n\nInstructions from: ~/.dsh/AGENTS.md\n\n${body}\n</system-reminder>`, { changes: [{ path: '~/.dsh/AGENTS.md', digest: 'original-digest' }] })
  Object.freeze(original)
  Object.freeze(original.content[0])
  const result = localizeMessage(original)
  assert.match(result.content[0].text, /不能覆盖系统、开发者或用户的直接指令/)
  assert.match(result.content[0].text, /指令来源：用户全局 AGENTS.md/)
  assert.equal(result.content[0].text.endsWith(body + '\n</system-reminder>'), true)
  assert.equal(result.id, original.id)
  assert.equal(result.source, original.source)
  assert.equal(localizeMessage(result), result)
})

test('普通用户消息、未知格式及技能正文保持原样，包括其中的宿主字样', () => {
  for (const original of [
    message('user', `<system-reminder>\n${intro}\n\n${body}`),
    message('skill', body),
    message('agent-instructions', 'A new SDK format\n' + body),
    message('model-selection', 'An unfamiliar model notice'),
    message('time-context', 'A new time format'),
  ]) assert.equal(localizeMessage(original), original)
})

test('初始、更新和空技能目录保留技能块及失效目录、直接调用的语义', () => {
  for (const update of [false, true]) for (const entries of [[], [{ name: 'dsh-session-maintenance', description: 'Keep DSH instructions unchanged.' }]]) {
    const catalog = '<available_skills>\n' + entries.map(e => `- \`${e.name}\`: ${e.description}`).join('\n') + '\n</available_skills>'
    const heading = update ? 'The available skill catalog changed.' : 'A skill is a reusable set of task-specific instructions.'
    const original = message('skill-catalog', `<system-reminder>\n${heading}\n\n${catalog}\n\noriginal generated guidance\n</system-reminder>`, { entries, update })
    const result = localizeMessage(original)
    assert.equal(result.content[0].text.includes(catalog), true)
    assert.equal(result.source, original.source)
    assert.match(result.content[0].text, /无需再次调用 skill 工具/)
    if (update) assert.match(result.content[0].text, /替代本会话此前的所有技能目录/)
    if (!entries.length) assert.match(result.content[0].text, /请勿使用旧目录中的名称/)
  }
})

test('时间、时区及来源分节保持一致，混合和缺失时区仍要求澄清', () => {
  for (const browser of [
    'Browser time zone for this request: America/Los_Angeles. Interpret otherwise-unqualified dates and times in this zone.',
    'Browser time zone for this request: mixed ["UTC","Asia/Shanghai"]. Ask the user to clarify otherwise-unqualified dates and times.',
    'Browser time zone for this request: unavailable. Ask the user to clarify otherwise-unqualified dates and times.',
  ]) {
    const text = `Time sampled while preparing turn 3, step 2: 2026-10-30T08:00:00-07:00[America/Los_Angeles]\n${browser}\nElapsed since the preceding step context: 2m 3s.`
    const result = localizeMessage(message('time-context', text, { sections: [{ name: 'time-context', text }] }))
    assert.match(result.content[0].text, /第 3 轮，第 2 步/)
    assert.match(result.content[0].text, /2026-10-30T08:00:00-07:00\[America\/Los_Angeles\]/)
    assert.match(result.content[0].text, /2m 3s/)
    assert.equal(result.source.sections[0].text, result.content[0].text)
    if (!browser.includes('Interpret')) assert.match(result.content[0].text, /请向用户确认/)
  }
})

test('模型切换说明保留切换事实与来源追踪，正文省略内部 provider 标识', () => {
  const original = message('model-selection', '[model changed: assistant turns above this point were generated by dsh-magpie/qoder; the session continues with workbuddy/deepseek]', { summary: 'dsh-magpie/qoder → workbuddy/deepseek' })
  const result = localizeMessage(original)
  assert.match(result.content[0].text, /模型已切换/)
  assert.doesNotMatch(result.content[0].text, /dsh-magpie|workbuddy/)
  assert.equal(result.source, original.source)
})

function host() {
  const listeners = new Map()
  return {
    listeners,
    on(name, callback, options) {
      const rows = listeners.get(name) ?? []
      if (options?.prepend) rows.unshift(callback)
      else rows.push(callback)
      listeners.set(name, rows)
      return () => { const index = rows.indexOf(callback); if (index >= 0) rows.splice(index, 1) }
    },
    emit(name, payload) { for (const callback of [...(listeners.get(name) ?? [])]) callback(payload) },
    async preStep(payload, initial) {
      const rows = [...(listeners.get('agent/pre-step') ?? [])]
      const run = index => index === rows.length ? Promise.resolve(initial) : rows[index](payload, () => run(index + 1))
      return run(0)
    },
  }
}

test('运行后包住既有模型切换监听器，按 agent 隔离，重复运行不累积并在销毁时释放', async () => {
  const ctx = host()
  apply(ctx)
  ctx.on('agent/pre-step', async (_payload, next) => {
    const decision = await next()
    return { ...decision, messages: [...decision.messages, message('model-selection', '[model changed: assistant turns above this point were generated by dsh-magpie/a; the session continues with workbuddy/b]')] }
  }, { prepend: true })
  const agent = {}
  const signal = new AbortController().signal
  ctx.emit('agent/status', { agent, status: 'running' })
  ctx.emit('agent/status', { agent, status: 'running' })
  assert.equal(ctx.listeners.get('agent/pre-step').length, 2)
  const result = await ctx.preStep({ agent, signal }, { kind: 'enter', messages: [] })
  assert.match(result.messages[0].content[0].text, /模型已切换/)
  const other = await ctx.preStep({ agent: {}, signal }, { kind: 'enter', messages: [] })
  assert.match(other.messages[0].content[0].text, /model changed/)
  ctx.emit('agent/disposed', { agent })
  assert.equal(ctx.listeners.get('agent/pre-step').length, 1)
})

test('拒绝、取消的步骤保留原决策，不添加或改写消息', async () => {
  const ctx = host()
  apply(ctx)
  const agent = {}
  ctx.emit('agent/status', { agent, status: 'running' })
  const controller = new AbortController()
  const rejected = { kind: 'reject', reason: 'owner rejected' }
  assert.equal(await ctx.preStep({ agent, signal: controller.signal }, rejected), rejected)
  controller.abort()
  const initial = { kind: 'enter', messages: [message('model-selection', '[model changed: assistant turns above this point were generated by a; the session continues with b]')] }
  assert.equal(await ctx.preStep({ agent, signal: controller.signal }, initial), initial)
})
